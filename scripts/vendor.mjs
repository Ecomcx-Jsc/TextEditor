#!/usr/bin/env node
// Vendor TipTap: the editor ships the exact TipTap (+ ProseMirror) build it was tested with inside this repo
// (node_modules committed for those packages only, listed in bundleDependencies). Installing @cms/editor from GitHub
// then never downloads TipTap from npm — if TipTap disappears or changes, every CMS still installs and builds.
// Nothing outside @cms/editor imports TipTap: plugins use defineBlock / registerBlock; the low-level classes are
// re-exported from @cms/editor.
//   node scripts/vendor.mjs        -> after `npm install` (e.g. a TipTap version bump): refresh the vendored set
// Then run `npm test` and commit node_modules/ changes together with package.json / package-lock.json.
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const pkgFile = path.join(root, "package.json");
const pkg = JSON.parse(fs.readFileSync(pkgFile, "utf8"));
const lock = JSON.parse(fs.readFileSync(path.join(root, "package-lock.json"), "utf8")).packages;

// Production closure of the TipTap packages the editor depends on
const direct = Object.keys(pkg.dependencies).filter((d) => d.startsWith("@tiptap/"));
const closure = new Set();
const walk = (name) => {
  const entry = lock[`node_modules/${name}`];
  if (!entry || closure.has(name)) return;
  closure.add(name);
  for (const d of Object.keys({ ...entry.dependencies, ...entry.optionalDependencies })) walk(d);
};
direct.forEach(walk);
const names = [...closure].sort();

// Keep built code only (no sourcemaps / TypeScript sources) — smaller repo, same runtime
let removed = 0;
const prune = (dir) => {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) { if (e.name === "src" && dir.split(path.sep).includes("node_modules")) { fs.rmSync(p, { recursive: true, force: true }); removed++; } else if (e.name !== "node_modules") prune(p); }
    else if (e.name.endsWith(".map")) { fs.rmSync(p); removed++; }
  }
};
for (const n of names) prune(path.join(root, "node_modules", n));

// .gitignore: commit exactly the vendored packages
const scopes = new Map();
for (const n of names) {
  const [a, b] = n.startsWith("@") ? n.split("/") : [null, n];
  if (a) scopes.set(a, [...(scopes.get(a) ?? []), b]);
}
const lines = ["# Generated by scripts/vendor.mjs — node_modules is ignored except the vendored TipTap/ProseMirror build", "node_modules/*", "node_modules/.package-lock.json", "node_modules/.cache"];
for (const n of names.filter((x) => !x.startsWith("@"))) lines.push(`!node_modules/${n}/`);
for (const [scope, list] of scopes) { lines.push(`!node_modules/${scope}/`, `node_modules/${scope}/*`); for (const b of list) lines.push(`!node_modules/${scope}/${b}/`); }
fs.writeFileSync(path.join(root, ".gitignore"), lines.join("\n") + "\n");

pkg.bundleDependencies = direct;
fs.writeFileSync(pkgFile, JSON.stringify(pkg, null, 2) + "\n");
console.log(`Vendored ${names.length} packages (${direct.length} direct TipTap packages in bundleDependencies), pruned ${removed} files/dirs.`);
